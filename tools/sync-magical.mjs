// Copies the Magical Chess rules the server must share with the app (src/power/rules.ts and src/power/online.ts) into
// the play-move server function, changing only the chess.js import to the form Supabase's Deno runtime needs.
// test/magical-online.test.ts fails if the copies have drifted. (Plan: 02_Design/MAGICAL-ONLINE-PLAN.md.)
//     node tools/sync-magical.mjs
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
export const forServer = (src) => '// GENERATED by tools/sync-magical.mjs from the app: do not edit here.\n'
  + src.replace('from "chess.js"', 'from "npm:chess.js@1.4.0"').replace('from "./rules"', 'from "./rules.ts"');
const out = new URL("../supabase/functions/play-move/power/", import.meta.url);
mkdirSync(out, { recursive: true });
for (const f of ["rules.ts", "online.ts"]) writeFileSync(new URL(f, out), forServer(readFileSync(new URL(`../src/power/${f}`, import.meta.url), "utf8")));
console.log("copied rules.ts and online.ts into supabase/functions/play-move/power/");
