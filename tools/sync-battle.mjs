// Copies the Puzzle Battle rules the server must share with the app (src/battle/rules.ts) into the puzzle-battle server
// function. test/battle.test.ts fails if the copy has drifted.
//     node tools/sync-battle.mjs
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
export const forServer = (src) => '// GENERATED by tools/sync-battle.mjs from the app (src/battle/rules.ts): do not edit here.\n' + src;
const out = new URL("../supabase/functions/puzzle-battle/", import.meta.url);
mkdirSync(out, { recursive: true });
writeFileSync(new URL("rules.ts", out), forServer(readFileSync(new URL("../src/battle/rules.ts", import.meta.url), "utf8")));
console.log("copied rules.ts into supabase/functions/puzzle-battle/");
