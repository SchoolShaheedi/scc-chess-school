// Builds the practice index for "Learn all the checkmates" (DECISIONS #137): scans every mate puzzle in the bank
// (mateIn1 to mateIn5), replays it to its final position, and for each mate keeps the easiest real positions of its
// pattern at mate in 1, 2 and 3 - by the bank's own theme tag where the bank has one, otherwise by the exact classifier
// (src/mates/classify.ts). Writes src/content/mates-index.json (the positions) and src/content/mates-counts.ts (how many).
//     MATES_BUILD=1 npx vitest run test/mates-build.test.ts
// Not part of the normal run: it reads the whole bank (50,050 puzzles) and rewrites two content files. The scan itself
// (the classifier's verdict on every mate) can be saved with MATES_SCAN=<path> for a look at the numbers.
import { writeFileSync } from "node:fs";
import { describe, it } from "vitest";
import { MATES } from "../src/content/mates";
import { scanBank } from "./mates-scan";

/** Positions kept per length for each mate: the easiest, so a child meets the gentlest first. */
const KEEP = 12;

describe.runIf(process.env.MATES_BUILD === "1")("mate index", () => {
  it("scans the bank and writes the practice index", () => {
    const rows = scanBank();
    if (process.env.MATES_SCAN) writeFileSync(process.env.MATES_SCAN, JSON.stringify(rows));
    const index: Record<string, [string, string, string, number][][]> = {};
    const counts: Record<string, number[]> = {};
    for (const m of MATES) {
      if (!m.practice) continue;
      const { theme, rule } = m.practice;
      const mine = rows.filter(r => (theme ? r.tags.includes(theme) : rule ? r.found.includes(rule) : false));
      const stages = [1, 2, 3].map(n => mine.filter(r => r.n === n).sort((a, b) => a.r - b.r || a.id.localeCompare(b.id)).slice(0, KEEP).map(r => [r.id, r.fen, r.moves, r.r] as [string, string, string, number]));
      if (stages.some(s => s.length)) { index[m.id] = stages; counts[m.id] = stages.map(s => s.length); }
    }
    writeFileSync("src/content/mates-index.json", JSON.stringify(index) + "\n");
    const lines = Object.entries(counts).map(([id, c]) => `  ${JSON.stringify(id)}: [${c.join(", ")}],`);
    writeFileSync("src/content/mates-counts.ts", `// How many practice positions each mate has at mate in 1, 2 and 3 (GENERATED by test/mates-build.test.ts - do not edit by hand).
// The positions themselves are in mates-index.json, loaded only when a mate's practice opens.
export const COUNTS: Record<string, number[]> = {
${lines.join("\n")}
};
`);
  }, 600000);
});
